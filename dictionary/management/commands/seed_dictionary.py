class Command(BaseCommand):
    """
    Django management command to seed the dictionary with demonstration data.

    Usage:
        python manage.py seed_dictionary
        python manage.py seed_dictionary --clear
    """

    help = 'Seeds the dictionary with demonstration data (~40 Hindi words).'

    def add_arguments(self, parser):
        parser.add_argument(
            '--clear',
            action='store_true',
            help='Clear existing demo entries before seeding.',
        )

    def handle(self, *args, **options):
        if options['clear']:
            deleted_count, _ = DictionaryEntry.objects.filter(is_demo_entry=True).delete()
            self.stdout.write(self.style.WARNING(f'Cleared {deleted_count} existing demo entries.'))

        created = 0
        updated = 0

        for data in DEMO_ENTRIES:
            entry, was_created = DictionaryEntry.objects.update_or_create(
                devanagari_word=data['devanagari_word'],
                defaults={
                    'romanised_word': data['romanised_word'],
                    'alternate_romanisations': data.get('alternate_romanisations', ''),
                    'english_meaning': data['english_meaning'],
                    'part_of_speech': data.get('part_of_speech', 'noun'),
                    'definition': data['definition'],
                    'example_sentence': data.get('example_sentence', ''),
                    'example_translation': data.get('example_translation', ''),
                    'etymology': data.get('etymology', ''),
                    'source_reference': data.get('source_reference', ''),
                    'is_demo_entry': True,
                }
            )
            if was_created:
                created += 1
            else:
                updated += 1

        self.stdout.write(
            self.style.SUCCESS(
                f'\nDictionary seeded successfully!\n'
                f'  Created: {created} entries\n'
                f'  Updated: {updated} entries\n'
                f'  Total demo entries: {DictionaryEntry.objects.filter(is_demo_entry=True).count()}\n\n'
                f'NOTE: These are DEMONSTRATION entries, not verified by Garuda Prakashan.'
            )
        )
